// An OCR Client (ocr.js)
// Since a single pixel on an HTML canvas might be hard to see,
// we can represent a single pixel for the ANN input as a square of 10x10 real pixels.
// Thus the real canvas is 200x200 pixels and it is represented by a 20x20 canvas from the perspective of the ANN.
// The variables below will help us keep track of these measurements.

var ocrDemo = {
  CANVA_WIDTH: 200,
  TRANSLATED_WIDTH: 20,
  PIXEL_WIDTH: 10, // TRANSLATED_WIDTH = CANVA_WIDTH / PIXEL_WIDTH

  // We can then outline the pixels in the new representation
  // so they are easier to see.
  // Here we have a blue grid generated by drawGrid().
  drawGrid: function (ctx) {
    for (
      var x = this.PIXEL_WIDTH, y = this.PIXEL_WIDTH;
      x < this.CANVAS_WIDTH;
      x += this.PIXEL_WIDTH, y += this.PIXEL_WIDTH
    ) {
      ctx.strokeStyle = this.BLUE;
      ctx.beginPath();
      ctx.moveTo(x, 0);
      ctx.lineTo(x, this.CANVAS_WIDTH);
      ctx.stroke();

      ctx.beginPath();
      ctx.moveTo(0, y);
      ctx.lineTo(this.CANVAS_WIDTH, y);
      ctx.stroke();
    }
  },

  // We also need to store the data drawn on the grid in a form that can be sent to the server.
  // For simplicity, we can have an array called data which labels an uncoloured, black pixel as 0
  // and a coloured white pixel as 1.
  // We also need some mouse listeners on the canvas so we know when to call fillSquare()
  // to colour a pixel white while a user is drawing a digit.
  // These listeners should keep track of whether we are in a drawing state and then call fillSquare()
  // to do some simple math and decide which pixels need to be filled in.

  onMouseMove: function (e, ctx, canvas) {
    if (!canvas.isDrawing) {
      return;
    }
    this.fillSquare(
      ctx,
      e.clientX - canvas.offsetLeft,
      e.clientY - canvas.offsetTop,
    );
  },

  onMouseDown: function (e, ctx, canvas) {
    canvas.isDrawing = true;
    this.fillSquare(
      ctx,
      e.clientX - canvas.offsetLeft,
      e.clientY - canvas.offsetTop,
    );
  },

  onMouseUp: function (e) {
    canvas.isDrawing = false;
  },

  fillSquare: function (ctx, x, y) {
    var xPixel = Math.floor(x / this.PIXEL_WIDTH);
    var yPixel = Math.floor(y / this.PIXEL_WIDTH);
    this.data[(xPixel - 1) * this.TRANSLATED_WIDTH + yPixel - 1] = 1;

    ctx.fillStyle = "#ffffff";
    ctx.fillRect(
      xPixel * this.PIXEL_WIDTH,
      yPixel * this.PIXEL_WIDTH,
      this.PIXEL_WIDTH,
      this.PIXEL_WIDTH,
    );
  },

  // Now we’re getting closer to the juicy stuff!
  // We need a function that prepares training data to be sent to the server.
  // Here we have a relatively straight forward train() function that does some error checking on the data to be sent,
  // adds it to trainArray and sends it off by calling sendData().

  train: function () {
    var digitVal = document.getElementById("digit").value;
    if (!digitVal || this.data.indexOf(1) < 0) {
      alert("Please type and draw a digit value in order to train the network");
      return;
    }
    this.trainArray.push({ y0: this.data, label: parseInt(digitVal) });
    this.trainingRequestCount++;

    // Time to send a training batch to the server.
    if (this.trainingRequestCount == this.BATCH_SIZE) {
      alert("Sending training data to server...");
      var json = {
        trainArray: this.trainArray,
        train: true,
      };

      this.sendData(json);
      this.trainingRequestCount = 0;
      this.trainArray = [];
    }
  },

  // An interesting design worth noting here is the use of trainingRequestCount, trainArray, and BATCH_SIZE. What’s happening here is that BATCH_SIZE is some pre-defined constant for how much training data a client will keep track of before it sends a batched request to the server to be processed by the OCR. The main reason to batch requests is to avoid overwhelming the server with many requests at once. If many clients exist (e.g. many users are on the ocr.html page training the system), or if another layer existed in the client that takes scanned drawn digits and translated them to pixels to train the network, a BATCH_SIZE of 1 would result in many, unnecessary requests. This approach is good because it gives more flexibility to the client, however, in practice, batching should also take place on the server, when needed. A denial of service (DoS) attack could occur in which a malicious client purposely sends many requests to the server to overwhelm it so that it breaks down.

  // We will also need a test() function. Similar to train(),
  // it should do a simple check on the validity of the data and send it off.
  // For test(), however, no batching occurs since users should be able
  // to request a prediction and get immediate results.

  test: function () {
    if (this.data.indexOf(1) < 0) {
      alert("Please draw a digit in order to test the network");
      return;
    }
    var json = {
      image: this.data,
      predict: true,
    };
    this.sendData(json);
  },

  // Finally, we will need some functions to make an HTTP POST request,
  // receive a response, and handle any potential errors along the way.

  receiveResponse: function (xmlHttp) {
    if (xmlHttp.status != 200) {
      alert("Server returned status " + xmlHttp.status);
      return;
    }
    var responseJSON = JSON.parse(xmlHttp.responseText);
    if (xmlHttp.responseText && responseJSON.type == "test") {
      alert(
        "The neural network predicts you wrote a \'" +
          responseJSON.result +
          "'",
      );
    }
  },

  onError: function (e) {
    alert("Error occurred while connecting to server: " + e.target.statusText);
  },

  sendData: function (json) {
    var xmlHttp = new XMLHttpRequest();
    xmlHttp.open("POST", this.HOST + ":" + this.PORT, false);
    xmlHttp.onload = function () {
      this.receiveResponse(xmlHttp);
    }.bind(this);
    xmlHttp.onerror = function () {
      this.onError(xmlHttp);
    }.bind(this);
    var msg = JSON.stringify(json);
    xmlHttp.setRequestHeader("Content-length", msg.length);
    xmlHttp.setRequestHeader("Connection", "close");
    xmlHttp.send(msg);
  },
};
